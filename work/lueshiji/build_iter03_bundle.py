from __future__ import annotations

import shutil
from pathlib import Path
from textwrap import dedent


ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "outputs" / "projects" / "lueshiji" / "iter-02"
OUT = ROOT / "outputs" / "projects" / "lueshiji" / "iter-03"


def write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dedent(content).strip() + "\n", encoding="utf-8")


def write_json(path: Path, payload: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(payload.strip() + "\n", encoding="utf-8")


def main() -> None:
    if not SRC.exists():
        raise SystemExit(f"missing source bundle: {SRC}")

    shutil.copytree(SRC, OUT, dirs_exist_ok=True)
